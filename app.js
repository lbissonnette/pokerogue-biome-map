  /**
   * The stretches ahead for the planner's mode.
   *
   * Classic: 10-wave stretches, boss on every wave ending in 0, gym leaders
   * and the champion block some of them, and the plan runs to wave 180.
   *
   * Endless: `hasShortBiomes` moves you every 5 waves, so only every other
   * stretch ends on a boss wave; every wave is wild (no trainers, no fixed
   * battles); after wave 49 (99, 149, …) the game forces the End biome for the
   * wave ending in 50, and End has no links, so the biome after it is random.
   * The plan therefore runs to the stretch just before the next End.
   */
  function schedule() {
    const { wave, gym, endless } = state.planner;
    if (endless) {
      const L = 5;
      const inEnd = wave % 50 === 0;
      const nextEnd = inEnd ? wave + 50 : Math.ceil(wave / 50) * 50;
      return {
        L,
        s: Math.ceil(wave / L),
        S: nextEnd / L - 1,
        nextEnd,
        inEnd,
        bossWaveOf: t => ((L * t) % 10 === 0 ? L * t : null),
        blocked: () => false,
        gymSet: new Set(),
      };
    }
    const gymSet = new Set(classic.gymWaves[gym] ?? []);
    const blockedSet = new Set([...gymSet, ...classic.fixedBattleWaves]);
    return {
      L: 10,
      s: Math.ceil(wave / 10),
      S: LAST_STRETCH,
      nextEnd: null,
      inEnd: false,
      bossWaveOf: t => 10 * t,
      blocked: w => blockedSet.has(w),
      gymSet,
    };
  }
