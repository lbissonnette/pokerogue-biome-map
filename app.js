  // ------------------------------------------------------------ pan & zoom
  function applyView() {
    const { x, y, k } = state.view;
    map.style.transform = `translate(${x}px, ${y}px) scale(${k})`;
  }

  function fitView() {
    const vw = viewport.clientWidth;
    const vh = viewport.clientHeight;
    if (vw === 0 || vh === 0) {
      // Not laid out yet (e.g. embedded in a frame that is still hidden); the
      // ResizeObserver below fits the map once it has a size.
      return;
    }
    const k = Math.min(vw / MAP_W, vh / MAP_H, 1.4) * 0.97;
    state.view = { k, x: (vw - MAP_W * k) / 2, y: (vh - MAP_H * k) / 2 };
    applyView();
  }

  function zoomBy(factor, px = viewport.clientWidth / 2, py = viewport.clientHeight / 2) {
    const v = state.view;
    const k2 = Math.min(3, Math.max(0.25, v.k * factor));
    v.x = px - (px - v.x) * (k2 / v.k);
    v.y = py - (py - v.y) * (k2 / v.k);
    v.k = k2;
    applyView();
  }

  function centerOn(key) {
    const p = positions.get(key);
    const v = state.view;
    if (v.k < 0.85) {
      v.k = 1;
    }
    v.x = viewport.clientWidth / 2 - p.cx * v.k;
    v.y = viewport.clientHeight / 2 - p.cy * v.k;
    applyView();
  }

