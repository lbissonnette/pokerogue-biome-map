  // Double battles: BattleScene.getDoubleBattleChance rolls 1-in-32 on a wave
  // ending in 0 (1-in-8 otherwise), every active lure divides that by 4, and
  // the result is clamped to at least 1 (a certain double). In a double both
  // enemies roll their species independently, so a double is two draws.
  const doubleChance = (boss, lures = state.planner.lures) => 1 / Math.max((boss ? 32 : 8) / 4 ** lures, 1);
  const doubleText = (boss, lures = state.planner.lures) => {
    const d = doubleChance(boss, lures);
    return d >= 1 ? "always" : `1 in ${Math.round(1 / d)}`;
  };
  /** Chance of hitting something with single-draw odds `p` when a double gives two draws. */
  const withDouble = (p, boss, lures = state.planner.lures) => {
    const d = doubleChance(boss, lures);
    return (1 - d) * p + d * (1 - (1 - p) ** 2);
  };

